        print("=" * 70)
        print("Step 1: 创建标准分类体系")
        print("=" * 70)

        # 删除旧分类
        s.run("MATCH (c:Category) DETACH DELETE c")

        all_paths = walk_taxonomy(TAXONOMY)
        cat_count = 0
        rel_count = 0

        for path, is_leaf in all_paths:
            cat_id = make_category_id(path)
            name = path[-1]
            level = len(path) - 1  # root=0, L1=1, ...

            s.run("""
                CREATE (c:Category {
                    id: $id, name: $name, level: $level,
                    is_leaf: $is_leaf, path: $path
                })
            """, id=cat_id, name=name, level=level,
                 is_leaf=is_leaf, path="/".join(path))
            cat_count += 1

            # 创建父子关系
            if len(path) > 1:
                parent_id = make_category_id(path[:-1])
                s.run("""
                    MATCH (p:Category {id: $pid})
                    MATCH (c:Category {id: $cid})
                    CREATE (p)-[:HAS_CHILD]->(c)
                """, pid=parent_id, cid=cat_id)
                rel_count += 1

        print(f"  ✓ 创建 {cat_count} 个 Category 节点")
        print(f"  ✓ 创建 {rel_count} 个 HAS_CHILD 关系")

        # ── Step 2: 获取现有 Topic 和其所属模块 ──
        print(f"\n{'=' * 70}")
        print("Step 2: 分类现有 Topic")
        print("=" * 70)

        # 从 JSON 文件构建完整的 Topic → 模块映射（覆盖所有 Topic）
