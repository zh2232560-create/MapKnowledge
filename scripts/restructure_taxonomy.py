        topic_module_map = {}
        for fpath in glob.glob("data/*_perpage.json"):
            with open(fpath, "r", encoding="utf-8") as f:
                data = json.load(f)
            # 找到 Chapter 名称
            ch_name = None
            for node in data.get("nodes", []):
                if node.get("label") == "Chapter":
                    ch_name = node["properties"]["name"]
                    break
            if not ch_name:
                continue
            # 将文件中所有 Topic 都映射到该 Chapter
            for node in data.get("nodes", []):
                if node.get("label") == "Topic":
                    topic_module_map[node["id"]] = ch_name
            # BELONGS_TO_CHAPTER 关系也记录（覆盖）
            for rel in data.get("relationships", []):
                if rel["type"] == "BELONGS_TO_CHAPTER":
                    tid_val = rel["start_node"]["value"]
                    topic_module_map[tid_val] = ch_name

        # 查询 Neo4j 中所有 Topic
        all_topics_in_db = list(s.run(
            "MATCH (t:Topic) RETURN t.id AS tid, t.name AS tname"
        ))
        topics = []
        for rec in all_topics_in_db:
            module = topic_module_map.get(rec["tid"], "常识判断")
            module = CHAPTER_TO_MODULE.get(module, module)
            topics.append({"tid": rec["tid"], "tname": rec["tname"], "chapter": module})
        print(f"  ✓ 从 JSON 文件构建了 {len(topics)} 个 Topic 的模块映射")

        # 删除旧 BELONGS_TO_CATEGORY 关系（重新建立）
        s.run("MATCH (:Topic)-[r:BELONGS_TO_CATEGORY]->(:Category) DELETE r")

        classified = 0
        unclassified_topics = []
        module_fallback = 0

        for rec in topics:
            tid = rec["tid"]
            tname = rec["tname"]
            chapter = rec["chapter"]
            module = CHAPTER_TO_MODULE.get(chapter, chapter)

            # 尝试深度分类
            cat_name = classify_topic(tname, module)

            if cat_name:
                # 找到分类 → 查找其在分类树中的完整路径
                cat_path = find_category_path(TAXONOMY, cat_name)
                if cat_path:
                    cat_id = make_category_id(cat_path)
                    s.run("""
                        MATCH (t:Topic {id: $tid})
                        MATCH (c:Category {id: $cid})
                        MERGE (t)-[:BELONGS_TO_CATEGORY]->(c)
                    """, tid=tid, cid=cat_id)
                    classified += 1
                    continue

            # 未匹配到深度分类 → 回退到 L1 模块
            l1_path = ["行政职业能力测验", module]
            l1_id = make_category_id(l1_path)
            s.run("""
                MATCH (t:Topic {id: $tid})
                MATCH (c:Category {id: $cid})
                MERGE (t)-[:BELONGS_TO_CATEGORY]->(c)
            """, tid=tid, cid=l1_id)
            module_fallback += 1
            unclassified_topics.append((tname, module))

        print(f"  ✓ 精确分类: {classified} 个 Topic")
        print(f"  ⚠ 回退到模块级: {module_fallback} 个 Topic")
        print(f"  总计: {classified + module_fallback} / {len(topics)}")

        # ── Step 3: 删除旧 Chapter 结构 ──
        print(f"\n{'=' * 70}")
        print("Step 3: 清理旧 Chapter 节点")
        print("=" * 70)

