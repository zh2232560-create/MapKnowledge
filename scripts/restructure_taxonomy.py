def walk_taxonomy(tree, path=None, results=None):
    """遍历分类树，返回 [(路径列表, 是否叶节点), ...]"""
    if path is None:
        path = []
    if results is None:
        results = []
    for name, children in tree.items():
        current = path + [name]
        is_leaf = not children
        results.append((current, is_leaf))
        if children:
            walk_taxonomy(children, current, results)
    return results


def make_category_id(path):
    """生成分类节点 ID"""
    return "cat_" + "_".join(path).replace(" ", "").replace("（", "(").replace("）", ")")


def find_category_path(tree, name, path=None):
    """在分类树中查找指定名称的完整路径"""
    if path is None:
        path = []
    for k, v in tree.items():
        current = path + [k]
        if k == name:
            return current
        if v:
            result = find_category_path(v, name, current)
            if result:
                return result
    return None


def classify_topic(topic_name, module_name):
    """
    将一个 Topic 分类到最深的匹配分类
    返回分类名称（CLASSIFICATION_RULES 的 key）或 None
    """
    topic_lower = topic_name.lower()

    # 按关键词长度倒序（优先匹配更具体的）
    candidates = []
    for cat_name, (keywords, mod) in CLASSIFICATION_RULES.items():
        if mod != module_name:
            continue
        for kw in keywords:
            if kw in topic_name or kw in topic_lower:
                # 匹配到了，记录分类名和关键词长度
                candidates.append((cat_name, len(kw), kw))
                break

    if not candidates:
        return None

    # 优先选择：关键词最长的匹配（更具体）
    candidates.sort(key=lambda x: -x[1])
    return candidates[0][0]


